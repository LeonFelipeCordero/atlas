"""Autogenerate detects foreign-key changes from the standard migration."""

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from atlas.persistence.database import create_engine, migrate_database
from atlas.persistence.models import Base


@pytest.mark.parametrize(
    "option,value", [("ondelete", "RESTRICT"), ("onupdate", "CASCADE"), ("deferrable", True)]
)
def test_autogenerate_detects_changed_foreign_key_actions(
    tmp_path: Path, option: str, value: str | bool
) -> None:
    path = tmp_path / "db.sqlite"
    migrate_database(path)
    config = Config(str(Path(__file__).resolve().parents[1] / "alembic.ini"))
    engine = create_engine(path)
    constraint = next(iter(Base.metadata.tables["repository_graphs"].foreign_key_constraints))
    original = getattr(constraint, option)
    try:
        with engine.connect() as connection:
            config.attributes["connection"] = connection
            command.check(config)  # Unchanged schema has no diffs.
            setattr(constraint, option, value)
            with pytest.raises(AutogenerateDiffsDetected, match="add_fk"):
                command.check(config)
    finally:
        setattr(constraint, option, original)
        engine.dispose()
